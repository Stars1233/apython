class AST:
    """The base of every node.

    CPython's constructor assigns positional arguments against _fields and
    then keyword arguments by name, accepting names that are in neither --
    the position attributes among them.  A field that was never assigned is
    an AttributeError on access rather than None, which is what
    ast.iter_fields and ast.dump both read it as.
    """

    __module__ = "ast"

    _fields = ()
    _attributes = ()

    def __init__(self, *args, **kwargs):
        fields = self._fields
        if len(args) > len(fields):
            raise TypeError(
                "%s constructor takes at most %d positional argument%s"
                % (type(self).__name__, len(fields),
                   "" if len(fields) == 1 else "s"))
        for name, value in zip(fields, args):
            setattr(self, name, value)
        for name, value in kwargs.items():
            setattr(self, name, value)


