bad = 0
for name, cp in CASES:
    got = eval('"\\N{' + name + '}"')
    if ord(got) != cp:
        bad += 1
        print("MISMATCH", name, hex(ord(got)), "wanted", hex(cp))
print("names checked:", len(CASES), "bad:", bad)

# Case folding is CPython's: the query is folded, the table is not.
print(ord("\N{latin small letter a}"), ord("\N{LATIN SMALL LETTER A}"))
