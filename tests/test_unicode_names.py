# The algorithmic family, which is parsed and not stored.
print(hex(ord("\N{CJK UNIFIED IDEOGRAPH-4E00}")), hex(ord("\N{CJK UNIFIED IDEOGRAPH-20000}")))

# Rejections.  A name that is a PREFIX of a real one must not resolve, which is
# what the length check in the scan is for.
for bad_name in ("NOT A REAL NAME", "LATIN CAPITAL LETTER", "SPACEX", "SPAC",
                 "CJK UNIFIED IDEOGRAPH-FFFFFF", "CJK UNIFIED IDEOGRAPH-ZZZZ"):
    try:
        eval('"\\N{' + bad_name + '}"')
        print("ACCEPTED (wrong):", bad_name)
    except SyntaxError:
        print("rejected:", bad_name)
