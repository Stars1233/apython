# The `marshal` module, and what it is for.
#
# The reader existed because a .pyc is marshalled; it was reachable only from
# the import system.  importlib calls marshal.loads on the bytes it read from
# a .pyc, and importlib is what twenty-one modules of CPython's Lib/ reach for
# -- usually a few lines after some other import that appeared to be the
# blocker.  So the reader becomes a module.
#
# Two types had to be added to it: a .pyc never holds a mutable constant, so
# a marshalled list or dict had never been seen.
